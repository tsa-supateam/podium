export const PROMPTS: Prompt[] = Object.entries(P).flatMap(([category, list]) => list.map((text) => ({ category, text })));
export const CATEGORIES = Object.keys(P);

export function randomPrompt(category: string | null = null, exclude = ""): Prompt {
  const pool = PROMPTS.filter((p) => (!category || p.category === category) && p.text !== exclude);
  return pool[Math.floor(Math.random() * pool.length)];
}
